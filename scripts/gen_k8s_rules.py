"""Wrap deploy/prometheus/rules/*.yml into a PrometheusRule for the Prometheus
Operator, so compose and Kubernetes run the same recording rules and alerts.

The `agent-canary` group is left out on Kubernetes: there the stable/canary
comparison is done by the Argo Rollouts AnalysisTemplate, per pod-template hash.

    python scripts/gen_k8s_rules.py           # write deploy/k8s/prometheusrule.yaml
    python scripts/gen_k8s_rules.py --check   # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "deploy" / "prometheus" / "rules"
OUT = ROOT / "deploy" / "k8s" / "prometheusrule.yaml"
K8S_ONLY_SKIP = {"agent-canary"}


def render() -> str:
    groups = []
    for path in sorted(RULES.glob("*.yml")):
        for group in yaml.safe_load(path.read_text())["groups"]:
            if group["name"] not in K8S_ONLY_SKIP:
                group = {k: v for k, v in group.items() if k != "interval"}  # operator default (30s)
                groups.append(group)
    doc = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "support-agent", "labels": {"release": "kube-prometheus-stack"}},
        "spec": {"groups": groups},
    }
    header = "# GENERATED by scripts/gen_k8s_rules.py from deploy/prometheus/rules/ - do not edit.\n"
    return header + yaml.safe_dump(doc, sort_keys=False, width=200)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale; run `make k8s-rules`")
        print("prometheusrule.yaml is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
