"""Turn one drill run into a Markdown report with every number traceable to
Prometheus, the controller's event log, and the alerts Alertmanager delivered.

    python scripts/drill_report.py --since 2026-10-17T10:00:00Z --until 2026-10-17T10:20:00Z
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
STATE = ROOT / "deploy" / "state"
OUT = ROOT / "docs" / "results"
PROM = "http://localhost:9090"
SINK = "http://localhost:9095"


def ts(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def q(expr: str, at: datetime) -> list[dict]:
    r = httpx.get(f"{PROM}/api/v1/query", params={"query": expr, "time": at.timestamp()}, timeout=10)
    r.raise_for_status()
    return r.json()["data"]["result"]


def per_release(since: datetime, until: datetime) -> list[dict]:
    w = f"{int((until - since).total_seconds())}s"
    g = "track, release"
    exprs = {
        "requests": f"sum by ({g}) (increase(agent_requests_total[{w}]))",
        "failures": f'sum by ({g}) (increase(agent_requests_total{{outcome!="success"}}[{w}]))',
        "loops": f'sum by ({g}) (increase(agent_guardrail_trips_total{{guardrail="loop_detected"}}[{w}]))',
        "p50": f"histogram_quantile(0.5, sum by ({g}, le) (rate(agent_request_duration_seconds_bucket[{w}])))",
        "p95": f"histogram_quantile(0.95, sum by ({g}, le) (rate(agent_request_duration_seconds_bucket[{w}])))",
        "cost": f"sum by ({g}) (increase(agent_llm_cost_usd_total[{w}]))",
        "steps": f"sum by ({g}) (increase(agent_steps_per_request_sum[{w}]))",
    }
    rows: dict[tuple[str, str], dict] = {}
    for name, expr in exprs.items():
        for s in q(expr, until):
            key = (s["metric"].get("track", "?"), s["metric"].get("release", "?"))
            rows.setdefault(key, {"track": key[0], "release": key[1]})[name] = float(s["value"][1])
    out = []
    for row in rows.values():
        n = row.get("requests", 0)
        if n < 1:
            continue
        out.append(
            {
                **row,
                "failure_ratio": row.get("failures", 0) / n,
                "loop_ratio": row.get("loops", 0) / n,
                "cost_per_request": row.get("cost", 0) / n,
                "steps_per_request": row.get("steps", 0) / n,
            }
        )
    return sorted(out, key=lambda r: (r["track"], r["release"]))


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--since", required=True)
    p.add_argument("--until", required=True)
    args = p.parse_args()
    since, until = ts(args.since), ts(args.until)

    events = [
        json.loads(line)
        for line in (STATE / "events.jsonl").read_text().splitlines()
        if since <= ts(json.loads(line)["ts"]) <= until
    ]
    try:
        alerts = [a for a in httpx.get(SINK, timeout=5).json() if since <= ts(a["received_at"]) <= until]
    except httpx.HTTPError:
        alerts = []
    rows = per_release(since, until)
    load_log = (
        (STATE / "drill-load.log").read_text().strip().split("--- sent")[-1]
        if (STATE / "drill-load.log").exists()
        else ""
    )

    OUT.mkdir(parents=True, exist_ok=True)
    stamp = since.strftime("%Y-%m-%d")
    (OUT / f"drill-{stamp}.json").write_text(
        json.dumps(
            {"since": args.since, "until": args.until, "events": events, "alerts": alerts, "releases": rows}, indent=2
        )
    )

    L = [f"# Release drill, {stamp}", ""]
    L.append(
        f"Window: {args.since} to {args.until}. Generated by `scripts/drill_report.py` from Prometheus, "
        f"`deploy/state/events.jsonl` and the alert sink; raw data in `drill-{stamp}.json`."
    )
    L += ["", "## Per release and track (whole drill window)", ""]
    L.append(
        "| Track | Release | Requests | Failure ratio | Loop ratio | p50 | p95 | Cost / request | Model calls / req |"
    )
    L.append("|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        L.append(
            f"| {r['track']} | {r['release']} | {r['requests']:.0f} | {r['failure_ratio']:.2%} | "
            f"{r['loop_ratio']:.2%} | {r.get('p50', 0):.2f}s | {r.get('p95', 0):.2f}s | "
            f"${r['cost_per_request']:.5f} | {r['steps_per_request']:.2f} |"
        )
    L += ["", "## Controller timeline", "", "| Time (UTC) | Event | Details |", "|---|---|---|"]
    for e in events:
        detail = {k: v for k, v in e.items() if k not in ("ts", "event", "checks")}
        L.append(f"| {e['ts'][11:19]} | `{e['event']}` | {', '.join(f'{k}={v}' for k, v in detail.items())} |")
        for c in e.get("checks", []):
            L.append(f"| | | {'ok' if c['passed'] else '**FAIL**'} {c['name']}: {c['observed']} (limit {c['limit']}) |")
    L += ["", "## Notifications delivered by Alertmanager", ""]
    if alerts:
        L += [
            "| Received (UTC) | Channel | Status | Alert | Severity | Track | Summary |",
            "|---|---|---|---|---|---|---|",
        ]
        for a in alerts:
            L.append(
                f"| {a['received_at'][11:19]} | {a['channel']} | {a['status']} | {a['alertname']} | "
                f"{a['severity']} | {a.get('track') or ''} | {a['summary']} |"
            )
    else:
        L.append("None.")
    if load_log:
        L += ["", "## Load generator (client side)", "", "```", "sent" + load_log, "```"]
    path = OUT / f"drill-{stamp}.md"
    path.write_text("\n".join(L) + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
